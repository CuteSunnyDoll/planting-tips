"""Validate data/plants.json and bundle it into data/plants-bundle.js."""

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA_PATH = os.path.join(ROOT, "data", "plants.json")
LIGHTING_PATH = os.path.join(ROOT, "data", "lighting-guide.json")
TOOLKIT_PATH = os.path.join(ROOT, "data", "toolkit-guide.json")
BUNDLE_PATH = os.path.join(ROOT, "data", "plants-bundle.js")

REQUIRED_PLANT_KEYS = [
    "id",
    "name_zh",
    "name_en",
    "botanical_name",
    "category",
    "scrap_regrow_verdict",
    "verdict_label",
    "best_starting_method",
    "starting_method_label",
    "water_only_limit",
    "light_requirement",
    "light_label",
    "expected_harvest_window",
    "difficulty",
    "myth_vs_reality",
    "steps",
    "pitfalls",
    "sources",
]


def validate_catalog(data: dict) -> list[str]:
    errors = []
    warnings = []
    plants = data.get("plants")
    if not isinstance(plants, list) or not plants:
        return ["'plants' must be a non-empty list."]

    seen_ids = set()
    for idx, plant in enumerate(plants):
        pid = plant.get("id", f"<index {idx}>")
        if pid in seen_ids:
            errors.append(f"[{pid}] Duplicate plant id.")
        seen_ids.add(pid)

        for key in REQUIRED_PLANT_KEYS:
            if key not in plant or plant[key] in (None, "", []):
                errors.append(f"[{pid}] Missing required field '{key}'.")

        sources = plant.get("sources", [])
        ref_ids = set()
        for src in sources:
            rid = src.get("ref_id")
            if not rid:
                errors.append(f"[{pid}] Source missing 'ref_id'.")
            elif rid in ref_ids:
                errors.append(f"[{pid}] Duplicate source ref_id '{rid}'.")
            else:
                ref_ids.add(rid)
            if not src.get("page_or_section"):
                errors.append(f"[{pid}] Source '{rid}' missing 'page_or_section'.")
            if not src.get("verified", False):
                warnings.append(f"[{pid}] Source '{rid}' ({src.get('title')}) is marked verified=false.")

        def check_refs(obj_name: str, obj: dict) -> None:
            refs = obj.get("source_refs", [])
            if not refs:
                errors.append(f"[{pid}] {obj_name} has empty source_refs.")
            for r in refs:
                if r not in ref_ids:
                    errors.append(f"[{pid}] {obj_name} references unknown ref_id '{r}'.")

        if isinstance(plant.get("myth_vs_reality"), dict):
            check_refs("myth_vs_reality", plant["myth_vs_reality"])

        for s in plant.get("steps", []):
            check_refs(f"step #{s.get('step_number')}", s)

        for i, p in enumerate(plant.get("pitfalls", []), 1):
            check_refs(f"pitfall #{i}", p)

    for w in warnings:
        print(f"WARN: {w}")
    return errors


def main() -> int:
    with open(DATA_PATH, "r", encoding="utf-8") as f:
        data = json.load(f)

    lighting_data = None
    if os.path.exists(LIGHTING_PATH):
        with open(LIGHTING_PATH, "r", encoding="utf-8") as f:
            lighting_data = json.load(f)

    toolkit_data = None
    if os.path.exists(TOOLKIT_PATH):
        with open(TOOLKIT_PATH, "r", encoding="utf-8") as f:
            toolkit_data = json.load(f)

    errors = validate_catalog(data)
    if errors:
        for e in errors:
            print(f"ERROR: {e}", file=sys.stderr)
        return 1

    bundle_js = (
        "// Auto-generated by scripts/validate_and_bundle.py — do not edit manually.\n"
        f"window.PLANTS_DATA = {json.dumps(data, ensure_ascii=False, indent=2)};\n"
        f"window.LIGHTING_DATA = {json.dumps(lighting_data, ensure_ascii=False, indent=2)};\n"
        f"window.TOOLKIT_DATA = {json.dumps(toolkit_data, ensure_ascii=False, indent=2)};\n"
    )
    with open(BUNDLE_PATH, "w", encoding="utf-8") as f:
        f.write(bundle_js)

    total_sources = sum(len(p["sources"]) for p in data["plants"])
    verified_sources = sum(sum(1 for s in p["sources"] if s.get("verified")) for p in data["plants"])
    print(
        f"OK: Validated {len(data['plants'])} plants, "
        f"{verified_sources}/{total_sources} verified sources. Wrote {os.path.relpath(BUNDLE_PATH, ROOT)}."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
